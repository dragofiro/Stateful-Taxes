// Generates the static assets for the landing-page map.
//
//   node scripts/build_landing_assets.mjs [path/to/flag/svgs]
//
// 1. Projects the US state outlines from `us-atlas` into SVG path strings and writes
//    src/components/landing/us_map_data.ts. The page ships these paths directly, so the
//    browser needs no map library and makes no network request for map data.
// 2. If a folder of flag SVGs is given (files named us-xx.svg, for example us-co.svg),
//    converts each one to a small WebP in public/flags/. The source SVGs are large
//    (some are over 600 KB), and the WebP files are about 20 KB each, so all flags can be
//    preloaded and appear at once on hover.
import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { geoAlbersUsa, geoMercator, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

const CODES = {
  Alabama: 'AL', Alaska: 'AK', Arizona: 'AZ', Arkansas: 'AR', California: 'CA', Colorado: 'CO',
  Connecticut: 'CT', Delaware: 'DE', 'District of Columbia': 'DC', Florida: 'FL', Georgia: 'GA',
  Hawaii: 'HI', Idaho: 'ID', Illinois: 'IL', Indiana: 'IN', Iowa: 'IA', Kansas: 'KS', Kentucky: 'KY',
  Louisiana: 'LA', Maine: 'ME', Maryland: 'MD', Massachusetts: 'MA', Michigan: 'MI', Minnesota: 'MN',
  Mississippi: 'MS', Missouri: 'MO', Montana: 'MT', Nebraska: 'NE', Nevada: 'NV', 'New Hampshire': 'NH',
  'New Jersey': 'NJ', 'New Mexico': 'NM', 'New York': 'NY', 'North Carolina': 'NC', 'North Dakota': 'ND',
  Ohio: 'OH', Oklahoma: 'OK', Oregon: 'OR', Pennsylvania: 'PA', 'Rhode Island': 'RI',
  'South Carolina': 'SC', 'South Dakota': 'SD', Tennessee: 'TN', Texas: 'TX', Utah: 'UT', Vermont: 'VT',
  Virginia: 'VA', Washington: 'WA', 'West Virginia': 'WV', Wisconsin: 'WI', Wyoming: 'WY',
  'Puerto Rico': 'PR',
};

const W = 975;
const H = 610;
const round = (n) => Math.round(n * 10) / 10;
const box = ([[x0, y0], [x1, y1]]) => ({ x: round(x0), y: round(y0), w: round(x1 - x0), h: round(y1 - y0) });

async function buildMapData() {
  const topo = JSON.parse(await readFile(require.resolve('us-atlas/states-10m.json'), 'utf8'));
  const fc = feature(topo, topo.objects.states);
  const proj = geoAlbersUsa().scale(1300).translate([W / 2, H / 2]);
  const gp = geoPath(proj).digits(1);

  const shapes = [];
  for (const f of fc.features) {
    const code = CODES[f.properties.name];
    if (!code || code === 'PR' || code === 'DC') continue;
    shapes.push({ code, d: gp(f), box: box(gp.bounds(f)) });
  }
  shapes.sort((a, b) => a.code.localeCompare(b.code));

  // Puerto Rico is outside the Albers USA projection, so it gets its own inset below Florida's east.
  const pr = fc.features.find((f) => f.id === '72');
  const prPath = geoPath(geoMercator().fitExtent([[836, 520], [958, 566]], pr)).digits(1);
  shapes.push({ code: 'PR', d: prPath(pr), box: box(prPath.bounds(pr)) });

  // D.C. is too small to hover, so it gets a round marker offset into the Atlantic.
  const [dcX, dcY] = proj([-77.0369, 38.9072]).map(round);

  const out = `// GENERATED by scripts/build_landing_assets.mjs. Do not edit by hand.
// Source: us-atlas states-10m (US Census Bureau cartographic boundaries), Albers USA projection.

export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};

export interface MapShape {
  code: string;
  d: string;
  box: { x: number; y: number; w: number; h: number };
}

/** The 50 states plus the Puerto Rico inset, keyed by postal code. */
export const MAP_SHAPES: readonly MapShape[] = ${JSON.stringify(shapes, null, 0).replace(/\},\{/g, '},\n  {')};

/** Where D.C. actually sits on the projected map. The marker is drawn offset from here. */
export const DC_ANCHOR = { x: ${dcX}, y: ${dcY} } as const;
`;
  const file = path.join(root, 'src/components/landing/us_map_data.ts');
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, out);
  console.log(`wrote ${path.relative(root, file)} (${(out.length / 1024).toFixed(0)} KB, ${shapes.length} shapes)`);
}

async function buildFlags(srcDir) {
  const sharp = (await import('sharp')).default;
  const outDir = path.join(root, 'public/flags');
  await mkdir(outDir, { recursive: true });
  const files = (await readdir(srcDir)).filter((f) => /^us-[a-z]{2}\.svg$/.test(f));
  let total = 0;
  for (const f of files) {
    const out = path.join(outDir, f.replace('.svg', '.webp'));
    const info = await sharp(path.join(srcDir, f), { density: 150 })
      .resize({ width: 640 })
      .webp({ quality: 80 })
      .toFile(out);
    total += info.size;
  }
  console.log(`wrote ${files.length} flags to public/flags (${(total / 1024).toFixed(0)} KB total)`);
}

await buildMapData();
if (process.argv[2]) await buildFlags(path.resolve(process.argv[2]));
